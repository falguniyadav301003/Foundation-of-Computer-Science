# MAIN PROGRAM
# ==============================

print("\n====================================")
print("          LAWS OF SETS")
print("====================================")

print("\nEntered Sets:")

for name, value in sets.items():
    print(f"Set {name} =", value)

print("Universal Set U =", U)


